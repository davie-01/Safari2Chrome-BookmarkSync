// Bundles the sync engine for the macOS agent (JavaScriptCore): classic script, no imports.
// Usage: cd extension && npm install && npm run bundle
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'); // repo root
const common = { bundle: true, format: 'iife', target: 'es2020', platform: 'neutral', legalComments: 'none', logLevel: 'warning' };
await build({ ...common, entryPoints: [path.join(root, 'extension/engine/host.js')], outfile: path.join(root, 'native/Resources/engine.js'),
  banner: { js: '// Generated by scripts/build-engine.mjs from extension/engine — do not edit.' } });
await build({ ...common, entryPoints: [path.join(root, 'extension/test/selftest-entry.js')], outfile: path.join(root, 'native/Tests/SafariBookmarksTests/Resources/engine-selftest.js'),
  banner: { js: '// Generated by scripts/build-engine.mjs — do not edit.' } });
import { copyFileSync } from 'node:fs';
copyFileSync(path.join(root, 'native/Resources/engine.js'), path.join(root, 'native/Tests/SafariBookmarksTests/Resources/engine.js'));
console.log('engine bundles written');
