// Generates Swift test fixtures so the Swift Safari editor is checked against the exact
// op semantics of the JS reference (FakeSafari). Run: node test/make-parity.mjs
import { writeFileSync } from 'node:fs';
import { env, cycle, choose } from './helpers.js';
import { randomEdit } from './fuzz-lib.js';
import { computeDiff } from '../engine/diff.js';
import { buildPlan } from '../engine/plan.js';
import { chromeTree } from './helpers.js';

function rng(seed) { return () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648); }
const cases = [];
for (const seed of [3, 5, 8, 13, 21, 34]) {
  const rnd = rng(seed);
  const e = env();
  let n = 0;
  e.safari.uuid = () => `00000000-0000-4000-8000-${String(++n).padStart(12, '0')}`;
  for (let i = 0; i < 6; i++) e.safari.add('root:bar', `seed${i}`, `https://seed${i}.test/`);
  await cycle(e);
  for (let round = 0; round < 25; round++) {
    for (let k = 0; k < 3; k++) await randomEdit(e, rnd, `${seed}_${round}_${k}`);
    const c = await chromeTree(e);
    const diff = computeDiff(e.state, e.safari.tree(), c.tree);
    const choices = choose({ 'del:': rnd() < 0.5 ? 'apply' : 'restore', conflict: 'useC' })(diff.items);
    const plan = buildPlan(diff, choices);
    if (plan.ops.s.length >= 1 && cases.length < 40) {
      const before = e.safari.tree();
      const probe = structuredClone(e.safari.roots);
      e.safari.apply(plan.ops.s);
      const after = e.safari.tree();
      e.safari.roots = probe;
      cases.push({ name: `seed${seed}-round${round}`, before, ops: plan.ops.s, after });
    }
    await cycle(e, { choose: choose({ 'del:': 'apply', conflict: 'useS' }) });
  }
}
const json = JSON.stringify(cases);
const out = `// Generated by extension/test/make-parity.mjs — do not edit.\nlet parityFixturesJSON = ###"${json}"###\n`;
writeFileSync(new URL('../../native/Tests/SafariBookmarksTests/ParityFixtures.swift', import.meta.url), out);
console.log(`${cases.length} cases, ${cases.reduce((a, c) => a + c.ops.length, 0)} ops`);
